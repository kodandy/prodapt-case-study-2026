#!/bin/sh
# Regenerates the gRPC Python code from services/gateway/proto with the locked grpcio-tools / mypy-protobuf.
# Runs inside the dev container (make proto). `--check` regenerates into a temp dir and fails on any diff
# (make proto-check, part of make ci), so the committed code always matches the .proto.
set -eu
cd "$(dirname "$0")/../../.."
PROTO_ROOT=services/gateway/proto
SRC_ROOT=services/gateway/src
PKG=gateway/merchant_api/pb
HEADER='# Generated by services/gateway/proto/generate.sh from payments.proto. Do not edit.
# ruff: noqa'

out=$SRC_ROOT
if [ "${1:-}" = "--check" ]; then
  out=$(mktemp -d)
  mkdir -p "$out/$PKG"
  cp "$SRC_ROOT/$PKG/__init__.py" "$out/$PKG/__init__.py"
fi

uv run --frozen python -m grpc_tools.protoc \
  -I "$PROTO_ROOT" \
  --python_out="$out" \
  --grpc_python_out="$out" \
  --mypy_out="$out" \
  --mypy_grpc_out="$out" \
  "$PROTO_ROOT/$PKG/payments.proto"

for file in payments_pb2.py payments_pb2.pyi payments_pb2_grpc.py payments_pb2_grpc.pyi; do
  path="$out/$PKG/$file"
  # mypy-protobuf tags lines for flake8-pyi (`# noqa: Y015`); ruff rejects codes it does not know (RUF102)
  { printf '%s\n' "$HEADER"; sed -E 's/ *# noqa: Y[0-9]+$//' "$path"; } > "$path.tmp"
  mv "$path.tmp" "$path"
done
uv run --frozen ruff format --quiet "$out/$PKG"

if [ "${1:-}" = "--check" ]; then
  for file in payments_pb2.py payments_pb2.pyi payments_pb2_grpc.py payments_pb2_grpc.pyi; do
    if ! cmp -s "$out/$PKG/$file" "$SRC_ROOT/$PKG/$file"; then
      echo "stale generated gRPC code: $SRC_ROOT/$PKG/$file (run make proto)" >&2
      exit 1
    fi
  done
  echo "generated gRPC code is up to date"
fi
